package com.creditsai.model;

import com.creditsai.exception.BusinessRuleException;
import com.creditsai.exception.ResourceNotFoundException;
import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToMany;
import jakarta.persistence.OrderBy;
import jakarta.persistence.Table;
import java.math.BigDecimal;
import java.math.RoundingMode;
import java.time.Instant;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.ToString;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.Generated;
import org.hibernate.annotations.UpdateTimestamp;
import org.hibernate.generator.EventType;

/**
 * A credit given to one {@link Client}, with its payment plan. Nothing is physically deleted: a
 * credit is archived instead, and only an inactive credit may be archived. The archive, restore,
 * status and collateral rules live here (encapsulation), so the service only loads the entity and
 * calls the method.
 *
 * <p>Only the plain input fields have setters; everything else changes through the methods below
 * and Hibernate. The credit number is generated by the database on insert.
 */
@Entity
@Table(name = "credits")
@Getter
@NoArgsConstructor
@ToString(exclude = {"client", "payments", "attachments"})
public class Credit implements AttachmentOwner {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /** {@code CR-{year}-{6-digit sequence}}, filled by the database default when the row is inserted. */
    @Generated(event = EventType.INSERT)
    @Column(name = "credit_number", nullable = false, insertable = false, updatable = false, length = 20)
    private String creditNumber;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "client_id", nullable = false)
    private Client client;

    @Setter
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private CreditType type;

    /** The principal, in the credit's currency. */
    @Column(nullable = false, precision = 12, scale = 2)
    private BigDecimal amount;

    @Setter
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 3)
    private CreditCurrency currency;

    /** The fixed annual nominal rate in percent, e.g. 5.25. */
    @Column(name = "interest_rate", nullable = false, precision = 7, scale = 4)
    private BigDecimal interestRate;

    @Setter
    @Column(name = "start_date", nullable = false)
    private LocalDate startDate;

    @Setter
    @Column(name = "end_date", nullable = false)
    private LocalDate endDate;

    /** The number of monthly instalments; follows the payment plan. */
    @Column(name = "term_months", nullable = false)
    private int termMonths;

    /** The regular instalment of the payment plan (the last one may differ by a few cents). */
    @Column(name = "monthly_payment", nullable = false, precision = 12, scale = 2)
    private BigDecimal monthlyPayment;

    @Column(name = "has_collateral", nullable = false)
    private boolean hasCollateral;

    /** The value of the collateral in the credit's currency; null without collateral. */
    @Column(name = "collateral_value", precision = 12, scale = 2)
    private BigDecimal collateralValue;

    @Column(name = "collateral_description", length = 500)
    private String collateralDescription;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 10)
    private CreditStatus status = CreditStatus.ACTIVE;

    @Column(nullable = false)
    private boolean archived;

    @Column(name = "archived_at")
    private Instant archivedAt;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @UpdateTimestamp
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    /** The payment plan rows, owned by this credit and replaced as a whole. */
    @Getter(AccessLevel.NONE)
    @OneToMany(mappedBy = "credit", cascade = CascadeType.ALL, orphanRemoval = true)
    @OrderBy("paymentNumber")
    private List<CreditPayment> payments = new ArrayList<>();

    /**
     * Returns the payment plan rows as a read-only view, ordered by payment number.
     *
     * @return the rows
     */
    public List<CreditPayment> getPayments() {
        return Collections.unmodifiableList(payments);
    }

    /**
     * Files attached to this credit. Like client attachments, they are physically deleted
     * (orphan removal) - an approved exception to the soft-delete rule.
     */
    @Getter(AccessLevel.NONE)
    @OneToMany(mappedBy = "credit", cascade = CascadeType.ALL, orphanRemoval = true)
    private List<CreditAttachment> attachments = new ArrayList<>();

    /**
     * Returns the attachments as a read-only view; change them only with {@link #attach} and
     * {@link #removeAttachment}.
     *
     * @return the attachments in no particular order
     */
    public List<CreditAttachment> getAttachments() {
        return Collections.unmodifiableList(attachments);
    }

    /** {@inheritDoc} */
    @Override
    public AttachmentOwnerType attachmentOwnerType() {
        return AttachmentOwnerType.CREDIT;
    }

    /** {@inheritDoc} */
    @Override
    public void ensureCanAttach(String fileName, long sizeBytes, int maxFiles, long maxTotalBytes) {
        AttachmentRules.ensureCanAttach(attachments, AttachmentOwnerType.CREDIT, fileName, sizeBytes, maxFiles,
                maxTotalBytes);
    }

    /** {@inheritDoc} */
    @Override
    public CreditAttachment attach(AttachmentDraft draft, int maxFiles, long maxTotalBytes) {
        ensureCanAttach(draft.fileName(), draft.sizeBytes(), maxFiles, maxTotalBytes);
        CreditAttachment attachment = CreditAttachment.builder()
                .fileName(draft.fileName())
                .contentType(draft.contentType())
                .sizeBytes(draft.sizeBytes())
                .sha256(draft.sha256())
                .uploadedBy(draft.uploadedBy())
                .build();
        attachment.assignTo(this);
        attachments.add(attachment);
        return attachment;
    }

    /**
     * Removes an attachment; its row is deleted when the transaction commits.
     *
     * @param attachmentId the id of the attachment
     * @return the removed attachment, so the caller can delete its file
     * @throws ResourceNotFoundException if this credit has no attachment with that id
     */
    public CreditAttachment removeAttachment(Long attachmentId) {
        CreditAttachment found = findAttachment(attachmentId);
        attachments.remove(found);
        return found;
    }

    /**
     * Finds one of this credit's attachments.
     *
     * @param attachmentId the id of the attachment
     * @return the attachment
     * @throws ResourceNotFoundException if this credit has no attachment with that id (it may belong
     *         to another credit)
     */
    public CreditAttachment findAttachment(Long attachmentId) {
        return AttachmentRules.find(attachments, attachmentId);
    }

    /**
     * Sets the principal, normalized to 2 decimals like the database column, so a response right
     * after saving shows the same value as a later read.
     *
     * @param amount the principal
     */
    public void setAmount(BigDecimal amount) {
        this.amount = amount.setScale(2, RoundingMode.HALF_UP);
    }

    /**
     * Sets the annual rate, normalized to 4 decimals like the database column.
     *
     * @param interestRate the rate in percent
     */
    public void setInterestRate(BigDecimal interestRate) {
        this.interestRate = interestRate.setScale(4, RoundingMode.HALF_UP);
    }

    /**
     * Assigns this credit to a client. A credit cannot be given to an archived client, but keeping
     * the client it already has is always allowed (so an archived credit stays editable).
     *
     * @param newClient the client that owns the credit
     * @throws BusinessRuleException if the client is archived and is not the current client
     */
    public void assignTo(Client newClient) {
        if (newClient.isArchived() && (client == null || !newClient.getId().equals(client.getId()))) {
            throw new BusinessRuleException("The client is archived, so it cannot be given a credit. Restore the client first.");
        }
        this.client = newClient;
    }

    /**
     * Sets the collateral. Value and description are required with collateral and are cleared
     * without it.
     *
     * @param has whether the credit is secured by collateral
     * @param value the collateral value in the credit's currency, ignored when {@code has} is false
     * @param description the collateral description, ignored when {@code has} is false
     * @throws BusinessRuleException if {@code has} is true and the value or description is missing
     */
    public void applyCollateral(boolean has, BigDecimal value, String description) {
        if (has && (value == null || description == null || description.isBlank())) {
            throw new BusinessRuleException("A credit with collateral needs a collateral value and description.");
        }
        this.hasCollateral = has;
        this.collateralValue = has ? value.setScale(2, RoundingMode.HALF_UP) : null;
        this.collateralDescription = has ? description : null;
    }

    /**
     * Replaces the whole payment plan.
     *
     * @param termInMonths the number of instalments
     * @param monthly the regular instalment
     * @param rows the new plan rows; their credit is set here
     */
    public void replacePayments(int termInMonths, BigDecimal monthly, List<CreditPayment> rows) {
        this.termMonths = termInMonths;
        this.monthlyPayment = monthly;
        payments.clear();
        rows.forEach(row -> {
            row.assignTo(this);
            payments.add(row);
        });
    }

    /**
     * Removes all plan rows without adding new ones, so the caller can flush the deletes before
     * inserting the new rows (the plan numbers are unique per credit).
     */
    public void clearPayments() {
        payments.clear();
    }

    /**
     * Changes the status. Activating needs a credit that is not archived and whose client is not
     * archived.
     *
     * @param target the new status
     * @throws BusinessRuleException if activating an archived credit, or a credit of an archived client
     */
    public void changeStatus(CreditStatus target) {
        if (target == CreditStatus.ACTIVE) {
            if (archived) {
                throw new BusinessRuleException("An archived credit cannot be activated. Restore it first.");
            }
            if (client.isArchived()) {
                throw new BusinessRuleException("The client of this credit is archived, so the credit cannot be activated.");
            }
        }
        this.status = target;
    }

    /**
     * Archives this credit (soft delete) and records when it happened.
     *
     * @throws BusinessRuleException if the credit is already archived or still active
     */
    public void archive() {
        if (archived) {
            throw new BusinessRuleException("This credit is already archived.");
        }
        if (status == CreditStatus.ACTIVE) {
            throw new BusinessRuleException("An active credit cannot be archived. Deactivate it first.");
        }
        archived = true;
        archivedAt = Instant.now();
    }

    /**
     * Brings an archived credit back; it stays inactive until an ADMIN activates it.
     *
     * @throws BusinessRuleException if the credit is not archived
     */
    public void restore() {
        if (!archived) {
            throw new BusinessRuleException("This credit is not archived.");
        }
        archived = false;
        archivedAt = null;
    }
}
